/**
 * Pin the reference engine to the bytes npm serves.
 *
 * Downloads the tarball for the `directive-v1` alias's version from the npm
 * registry, checks its sha512 equals the integrity pnpm-lock.yaml records,
 * and writes `v1-pin.json`: the version, that integrity, and the sha256 of
 * every file in the tarball. The engine-identity self test then proves the
 * installed package is exactly those files, so an override, a patch or a
 * hand edit in node_modules cannot pass as the release.
 *
 * Run it when the alias moves (README: the v1 pin rule). The result is a
 * harness file, so the PR needs the oracle-change label.
 *
 * Usage: pnpm --filter @directive-run/conformance pin:v1
 */

import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import {
  mkdtempSync,
  readFileSync,
  readdirSync,
  rmSync,
  statSync,
  writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { join, relative } from "node:path";
import { defaultRepoRoot } from "../lib/core-entries.js";
import { lockIntegrity } from "../lib/lockfile.js";

const conformanceRoot = join(defaultRepoRoot, "packages/conformance");
const pkg = JSON.parse(
  readFileSync(join(conformanceRoot, "package.json"), "utf8"),
);
const version = (pkg.devDependencies["directive-v1"] as string).replace(
  /^npm:@directive-run\/core@/,
  "",
);
const integrity = lockIntegrity(
  readFileSync(join(defaultRepoRoot, "pnpm-lock.yaml"), "utf8"),
  "@directive-run/core",
  version,
);
if (!integrity) {
  throw new Error(
    `pnpm-lock.yaml has no integrity for @directive-run/core@${version}`,
  );
}

const url = `https://registry.npmjs.org/@directive-run/core/-/core-${version}.tgz`;
const response = await fetch(url);
if (!response.ok) {
  throw new Error(`${url}: ${response.status}`);
}
const tarball = Buffer.from(await response.arrayBuffer());
const actual = `sha512-${createHash("sha512").update(tarball).digest("base64")}`;
if (actual !== integrity) {
  throw new Error(
    `${url} has integrity ${actual}; the lockfile records ${integrity}`,
  );
}

const dir = mkdtempSync(join(tmpdir(), "directive-v1-"));
try {
  writeFileSync(join(dir, "package.tgz"), tarball);
  execFileSync("tar", ["-xzf", "package.tgz"], { cwd: dir });
  const root = join(dir, "package");
  const walk = (d: string): string[] =>
    readdirSync(d).flatMap((n) => {
      const full = join(d, n);

      return statSync(full).isDirectory() ? walk(full) : [full];
    });
  const files = Object.fromEntries(
    walk(root)
      .map((f) => [
        relative(root, f),
        createHash("sha256").update(readFileSync(f)).digest("hex"),
      ])
      .sort(([a], [b]) => (a as string).localeCompare(b as string)),
  );
  writeFileSync(
    join(conformanceRoot, "v1-pin.json"),
    `${JSON.stringify(
      {
        $comment:
          "Generated by scripts/pin-v1.ts from the npm tarball. The engine-identity self test checks the installed directive-v1 against it.",
        version,
        integrity,
        files,
      },
      null,
      2,
    )}\n`,
  );
  console.log(
    `[pin-v1] @directive-run/core@${version}: ${Object.keys(files).length} files, ${integrity.slice(0, 20)}…`,
  );
} finally {
  rmSync(dir, { recursive: true, force: true });
}
