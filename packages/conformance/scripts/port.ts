/**
 * Port core's black-box tests into the conformance suite.
 *
 * Copies (core keeps its own tests on 1.x) and rewrites only core import
 * specifiers, plus the environment rewrites declared in lib/rewrites.ts.
 * `check-expects.ts` re-runs the same classification and fails on any
 * difference, so what this writes is never trusted on its own.
 *
 * Re-runnable: regenerates `tests/`, `layers.json`, `scripts/manifest.json`
 * and `scripts/classification.json` from scratch every time.
 *
 * Usage: pnpm --filter @directive-run/conformance port
 */

import { execFileSync } from "node:child_process";
import { mkdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { type Category, classify } from "../lib/classify.js";
import { defaultRepoRoot } from "../lib/core-entries.js";

const repoRoot = defaultRepoRoot;
const conformanceRoot = join(repoRoot, "packages/conformance");

const result = classify(repoRoot);
if (result.problems.length > 0) {
  for (const p of result.problems) {
    console.error(`✗ ${p}`);
  }
  process.exit(1);
}

rmSync(join(conformanceRoot, "tests"), { recursive: true, force: true });
const manifest: Record<string, string> = {};
for (const port of result.ports) {
  const dest = join(conformanceRoot, port.out);
  mkdirSync(dirname(dest), { recursive: true });
  writeFileSync(dest, port.text);
  manifest[port.out] = port.original;
}

const json = (value: unknown) => `${JSON.stringify(value, null, 2)}\n`;
const written = {
  manifest: join(conformanceRoot, "scripts/manifest.json"),
  classification: join(conformanceRoot, "scripts/classification.json"),
  layers: join(conformanceRoot, "layers.json"),
};
writeFileSync(written.manifest, json(manifest));
writeFileSync(written.classification, json(result.classified));
writeFileSync(
  written.layers,
  json({
    $comment:
      "Generated by scripts/port.ts from layers.rules.json; do not edit. Each test's layer is the highest feature it uses.",
    files: result.layers,
  }),
);

// Rewritten import lines are not in sorted order. Let the repo's formatter
// settle them so `pnpm lint` stays clean; check-expects compares imports as
// sets and flags anything else the formatter changed. Paths are relative to
// the repo root: biome.json ignores any path containing `worktrees`, so an
// absolute path inside a git worktree would be skipped.
execFileSync(
  join(repoRoot, "node_modules/.bin/biome"),
  [
    "check",
    "--write",
    relative(repoRoot, join(conformanceRoot, "tests")),
    ...Object.values(written).map((p) => relative(repoRoot, p)),
  ],
  { cwd: repoRoot, stdio: "inherit" },
);

const count = (c: Category) =>
  result.classified.filter((x) => x.category === c);
const sum = (c: Category) => count(c).reduce((n, x) => n + x.cases, 0);
console.log(
  `[port] ${result.classified.length} files: ${(
    ["black-box", "internals", "white-box", "packaging"] as Category[]
  )
    .map((c) => `${c} ${count(c).length} (${sum(c)} cases)`)
    .join(", ")}`,
);
